Function Colorize($ForeGroundColor) {
    $color = $Host.UI.RawUI.ForegroundColor
    $Host.UI.RawUI.ForegroundColor = $ForeGroundColor

    if ($args) {
        Write-Output $args
    }

    $Host.UI.RawUI.ForegroundColor = $color
}


